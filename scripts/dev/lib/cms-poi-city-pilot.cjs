function readRegistry() {
  try {
    if (!fs.existsSync(REGISTRY)) return null;
    return JSON.parse(fs.readFileSync(REGISTRY, 'utf8'));
  } catch {
    return null;
  }
}

function resolveCityZhFromArgv(argv = process.argv) {
  const i = argv.indexOf('--city-zh');
  if (i >= 0 && argv[i + 1]) return argv[i + 1];
  return null;
}

function getCityPilot(cityZh) {
  const pilot = CITY_PILOTS[cityZh];
  if (!pilot) throw new Error(`unknown city pilot: ${cityZh}`);
  return pilot;
}

function resolveActiveCityPilot(argv = process.argv) {
  const explicit = resolveCityZhFromArgv(argv);
  if (explicit) return getCityPilot(explicit);
  const reg = readRegistry();
  if (reg?.active_city?.city_zh) return getCityPilot(reg.active_city.city_zh);
  return getCityPilot('东京');
}

