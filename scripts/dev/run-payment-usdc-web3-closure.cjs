#!/usr/bin/env node
/**
 * PAYMENT-USDC-WEB3-CLOSURE — re-run deep audit + record P0/P1 closure manifest.
 *
 *   node scripts/dev/run-payment-usdc-web3-closure.cjs
 */
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const ROOT = path.join(__dirname, '../..');
const STAMP = new Date().toISOString();
const EVID_ROOT = path.join(ROOT, 'evidence/GO_production_readiness/payment-deep-audit');
const RUN_DIR = path.join(EVID_ROOT, `closure-${STAMP.replace(/[:.]/g, '-').slice(0, 19)}`);

function mkdirp(p) {
  fs.mkdirSync(p, { recursive: true });
}

function readJson(p) {
  try {
    return JSON.parse(fs.readFileSync(p, 'utf8'));
  } catch {
    return null;
  }
}

function main() {
  mkdirp(RUN_DIR);

  const auditRun = spawnSync(process.execPath, [path.join(__dirname, 'run-payment-usdc-web3-deep-audit.cjs')], {
    cwd: ROOT,
    encoding: 'utf8',
  });
  fs.writeFileSync(path.join(RUN_DIR, 'audit-rerun.log'), `${auditRun.stdout || ''}${auditRun.stderr || ''}`, 'utf8');

  const postAudit = readJson(path.join(EVID_ROOT, 'PAYMENT-USDC-WEB3-DEEP-AUDIT-LATEST.json')) || {};

  const closureItems = [
    {
      id: 'CLOSE-P0-DOCS',
      title: 'Docs demote Stripe from Production BLOCKER / 必达',
      paths: [
        'docs/runbook/PRODUCTION-READINESS-REPORT.md',
        'docs/runbook/PRODUCTION-READINESS-MASTER-GAP-REPORT.md',
        'docs/handbook/engineering/148-PI3-005-Production-Scope-Decision-Report.md',
        'docs/runbook/TT-RELEASE-PIPELINE.md',
      ],
      status: 'CLOSED',
    },
    {
      id: 'CLOSE-P0-REGISTRY',
      title: 'Registry sync — PRM-WEB3 CLOSED · PRM-STR g3_domain · machine keys',
      paths: [
        'registry/production-readiness-master-matrix.v1.yaml',
        'registry/production-go-four-gate-framework.v1.yaml',
        'registry/production-go-remaining-work.v1.yaml',
        'registry/hat-six-role-matrix.v1.yaml',
      ],
      status: 'CLOSED',
    },
    {
      id: 'CLOSE-P1-UX',
      title: 'USDC default currency + pay/chain copy + pay_mockPay_disabledNotice',
      paths: ['frontend/locales/en.ts', 'frontend/locales/zh.ts'],
      status: 'CLOSED',
    },
    {
      id: 'CLOSE-P1-TESTS',
      title: 'HAT / E2E / IT payment rail annotations (mock-pay = sandbox only)',
      paths: [
        'registry/hat-six-role-matrix.v1.yaml',
        'frontend/e2e/f024-f025-f026-request.spec.ts',
        'crates/api/src/routes/market_subsite_catalog_db_api_tests/acquisition_pd009_full_flow.rs',
      ],
      status: 'CLOSED',
    },
  ];

  const manifest = {
    schema: 'traveltrust.payment_usdc_web3_closure.v1',
    recorded_utc: STAMP,
    run_dir: path.relative(ROOT, RUN_DIR).replace(/\\/g, '/'),
    verdict:
      (postAudit.summary?.blockers_p0 || 0) === 0 && (postAudit.summary?.blockers_p1 || 0) === 0
        ? 'PAYMENT_USDC_WEB3_CLOSURE_PASS'
        : 'PAYMENT_USDC_WEB3_CLOSURE_PARTIAL',
    ssot: 'registry/payment-architecture-classification.v1.yaml',
    architecture_truth: {
      core: 'Web3 USDC Escrow (approve → deposit → release → FeeRouter → settlement)',
      optional: 'Stripe onboarding P1 only',
      sandbox: 'mock-pay chain_off only — forbidden prod',
    },
    closure_items: closureItems,
    post_audit: postAudit.summary || {},
    post_audit_verdict: postAudit.verdict,
    g3_02: readJson(path.join(ROOT, 'evidence/GO_production_readiness/G3-02/WEB3-PAYMENT-PRODUCTION-READINESS-LATEST.json')),
    discipline: { business_logic_changed: false, docs_registry_i18n_test_annotations_only: true },
  };

  fs.writeFileSync(path.join(RUN_DIR, 'PAYMENT-USDC-WEB3-CLOSURE.json'), `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');
  fs.writeFileSync(path.join(EVID_ROOT, 'PAYMENT-USDC-WEB3-CLOSURE-LATEST.json'), `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');

  const md = [
    '# PAYMENT-USDC-WEB3-CLOSURE',
    '',
    `**Recorded:** ${STAMP}`,
    `**Verdict:** \`${manifest.verdict}\``,
    '',
    '## Closure items',
    '',
    ...closureItems.map((c) => `- **${c.id}** · ${c.title} · \`${c.status}\``),
    '',
    '## Post-audit',
    '',
    '```json',
    JSON.stringify(postAudit.summary || {}, null, 2),
    '```',
    '',
    '*Generated by scripts/dev/run-payment-usdc-web3-closure.cjs*',
    '',
  ].join('\n');
  fs.writeFileSync(path.join(EVID_ROOT, 'PAYMENT-USDC-WEB3-CLOSURE-LATEST.md'), md, 'utf8');

  console.log(JSON.stringify({ verdict: manifest.verdict, post_audit: postAudit.summary }, null, 2));
  process.exit(manifest.verdict === 'PAYMENT_USDC_WEB3_CLOSURE_PASS' ? 0 : 2);
}

main();
