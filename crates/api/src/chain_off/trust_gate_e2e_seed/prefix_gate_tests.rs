use uuid::Uuid;

use super::prefix::is_trust_gate_seeded_order_id;

/// 与 `seed_trust_gate_e2e_fixtures` 内全部 `o_*` / `o_risk_*` 订单 UUID **逐字一致**。
#[test]
fn fixture_order_ids_match_pg_upsert_prefix_gate() {
    const IDS: &[&str] = &[
        "f0e0c201-0001-4001-8001-000000000001",
        "f0e0c201-0001-4001-8001-000000000002",
        "f0e0c201-0001-4001-8001-000000000003",
        "f0e0c201-0001-4001-8001-000000000004",
        "f0e0c201-0001-4001-8001-000000000005",
        "f0e0c201-0001-4001-8001-000000000006",
        "f0e0c201-0001-4001-8001-000000000007",
        "f0e0c201-0001-4001-8001-000000000008",
        "f0e0c201-0001-4001-8001-000000000009",
        "f0e0c201-0001-4001-8001-00000000000a",
        "f0e0c201-0001-4001-8001-00000000000b",
        "f0e0c201-0001-4001-8001-00000000000c",
        "f0e0c201-0001-4001-8001-00000000000d",
        "f0e0c201-0001-4001-8001-00000000000e",
        "f0e0c201-0001-4001-8001-00000000000f",
        "f0e0c201-0001-4001-8001-000000000010",
        "f0e0c201-0001-4001-8001-000000000011",
        "f0e0c201-0001-4001-8001-000000000012",
        "f0e0c201-0001-4001-8001-000000000013",
        "f0e0e401-0001-4001-8001-000000000001",
        "f0e0e401-0001-4001-8001-000000000002",
        "f0e0e401-0001-4001-8001-000000000003",
        "f0e0e401-0001-4001-8001-000000000004",
    ];
    for s in IDS {
        let id = Uuid::parse_str(s).expect("fixture order uuid");
        assert!(
            is_trust_gate_seeded_order_id(id),
            "order {s} must match is_trust_gate_seeded_order_id or PG upsert skips it → possible evidence_receipts FK WARN"
        );
    }
}
